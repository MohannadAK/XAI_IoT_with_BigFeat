"""
Every number in the manuscript's tables, recomputed from the committed results.

  python experiments/paper_tables.py   -> results/paper_tables.md

Reads results/ceiling.csv, results/round2 (N-BaIoT in-fold top-20, Edge-IIoTset) and
results/round3 (UNSW-NB15). Run experiments/analyze.py on both rounds first.
"""
import os
import sys

import numpy as np
import pandas as pd

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import analyze as A  # noqa: E402

REPO = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
RES = os.path.join(REPO, "results")
OUT = os.path.join(RES, "paper_tables.md")
TASKS = [("nbaiot", "infold20", "N-BaIoT"), ("edgeiiot", "all", "Edge-IIoTset"), ("unswnb15", "all", "UNSW-NB15")]
ORDER = ["original", "split10", "lgbm", "bigfeat", "bigfeat_raw", "tpot", "both", "both_raw", "bigfeat_auto",
         "tpot_auto"]
NAME = dict(original="Baseline", split10="ExtraTrees, split 10", lgbm="LightGBM", bigfeat="BigFeat (scaled)",
            bigfeat_raw="BigFeat (unscaled)", tpot="TPOT (ExtraTrees)", both="BigFeat (scaled) + TPOT",
            both_raw="BigFeat (unscaled) + TPOT", bigfeat_auto="BigFeat, model chosen",
            tpot_auto="TPOT, full search")
# (dataset, automated configuration, configuration that matches it) as in the cost-to-match table
COST_TO_MATCH = [("nbaiot", "tpot", "original"), ("nbaiot", "bigfeat_raw", "original"),
                 ("edgeiiot", "tpot", "split10"), ("edgeiiot", "both_raw", "lgbm"),
                 ("unswnb15", "bigfeat_auto", "lgbm"), ("unswnb15", "tpot_auto", "lgbm")]


def load():
    runs, summ, unit_tests = [], [], []
    for r in ("round2", "round3"):
        d = os.path.join(RES, r, "summary")
        runs.append(pd.read_csv(os.path.join(d, "all_runs.csv")))
        summ.append(pd.read_csv(os.path.join(d, "summary_by_unit_config.csv")))
        unit_tests.append(pd.read_csv(os.path.join(d, "per_unit_tests.csv")))
    pw = pd.read_csv(os.path.join(RES, "round2", "summary", "across_unit_pairwise.csv"))
    runs = pd.concat(runs)
    runs["unit"] = runs.unit.astype(str)
    keep = lambda df: pd.concat([df[(df.dataset == ds) & (df.feature_mode == fm)] for ds, fm, _ in TASKS])
    return keep(runs), keep(pd.concat(summ)), keep(pd.concat(unit_tests)), pw


def md(df):
    cols = list(df.columns)
    rows = ["| " + " | ".join(cols) + " |", "|" + "---|" * len(cols)]
    rows += ["| " + " | ".join("" if pd.isna(v) else str(v) for v in r) + " |" for r in df.itertuples(index=False)]
    return "\n".join(rows)


def pair(runs, ds, a, b, metric="f1_macro"):
    """Mean difference a - b over seeds and the corrected resampled t-test p (single-task datasets)."""
    s = runs[runs.dataset == ds]
    x = s[s.config == a].set_index("seed")[metric]
    y = s[s.config == b].set_index("seed")[metric]
    d = (x - y).dropna().values
    return d.mean(), int((d > 0).sum()), A.corrected_t(d)[1]


def main():
    runs, summ, ut, pw = load()
    out = ["# Numbers in the manuscript's tables", "",
           "Generated by `experiments/paper_tables.py`. N-BaIoT is the in-fold top-20 setting, averaged "
           "over the 9 devices.", ""]

    # Datasets: upper bound and baseline
    ceil = pd.read_csv(os.path.join(RES, "ceiling.csv"))
    rows = []
    for ds, fm, name in TASKS:
        c = ceil[(ceil.dataset == ds) & ceil.feature_mode.isin(["raw115_seed0", "all_seed0"])].max_macro_f1.mean()
        b = summ[(summ.dataset == ds) & (summ.config == "original")].f1_macro__mean.mean()
        rows.append(dict(dataset=name, upper_bound=round(c, 4), baseline=round(b, 4), headroom=round(c - b, 4)))
    out += ["## Datasets: upper bound on Macro-F1 and baseline", "", md(pd.DataFrame(rows)), ""]

    # Change in Macro-F1
    rows = []
    for c in ORDER[1:]:
        r = dict(configuration=NAME[c])
        p = pw[(pw.dataset == "nbaiot") & (pw.feature_mode == "infold20") & (pw.metric == "f1_macro") & (pw.config == c)]
        if len(p):
            r.update({"N-BaIoT dF1": f"{p.mean_diff.iloc[0]:+.5f}", "N-BaIoT P_ROPE": f"{p.p_rope.iloc[0]:.2f}",
                      "N-BaIoT p_Holm (Wilcoxon)": f"{p.wilcoxon_p_holm.iloc[0]:.3f}"})
        for ds, _, name in TASKS[1:]:
            t = ut[(ut.dataset == ds) & (ut.metric == "f1_macro") & (ut.config == c)]
            if len(t):
                t = t.iloc[0]
                r.update({f"{name} dF1 (wins)": f"{t.mean_diff:+.4f} ({t.wins})", f"{name} p_Holm": f"{t.p_holm:.3f}",
                          f"{name} P_ROPE": f"{t.p_rope:.2f}", f"{name} P_better": f"{t.p_better:.2f}"})
        rows.append(r)
    out += ["## Change in Macro-F1 relative to the baseline", "", md(pd.DataFrame(rows)), ""]

    # Comparisons with LightGBM
    rows = []
    for ds, c in [("edgeiiot", "tpot"), ("edgeiiot", "split10"), ("edgeiiot", "both_raw"), ("unswnb15", "bigfeat_auto"),
                  ("unswnb15", "tpot_auto")]:
        m, w, p = pair(runs, ds, c, "lgbm")
        rows.append(dict(dataset=ds, configuration=NAME[c], dF1=f"{m:+.4f}", wins=f"{w}/5", p=f"{p:.3f}"))
    m, w, p = pair(runs, "edgeiiot", "tpot", "split10")
    rows.append(dict(dataset="edgeiiot", configuration="TPOT (ExtraTrees) vs ExtraTrees, split 10", dF1=f"{m:+.4f}",
                     wins=f"{w}/5", p=f"{p:.3f}"))
    out += ["## Comparisons with LightGBM (last row: TPOT vs split 10; corrected resampled t-test, uncorrected p)", "", md(pd.DataFrame(rows)), ""]

    # Training time
    rows = []
    for c in ORDER:
        r = dict(configuration=NAME[c])
        for ds, _, name in TASKS:
            s = summ[summ.dataset == ds].groupby("config").train_time_s__mean.mean()
            if c in s:
                r[f"{name} s"] = f"{s[c]:,.0f}"
                r[f"{name} x"] = f"{s[c] / s['original']:.1f}"
        rows.append(r)
    out += ["## Training time (s) and ratio to the baseline", "", md(pd.DataFrame(rows)), ""]

    # Cost to match
    rows = []
    for ds, c, m in COST_TO_MATCH:
        s = summ[summ.dataset == ds].groupby("config").train_time_s__mean.mean()
        if ds == "nbaiot":
            p = pw[(pw.dataset == ds) & (pw.feature_mode == "infold20") & (pw.metric == "f1_macro") & (pw.config == c)]
            test = f"P_ROPE={p.p_rope.iloc[0]:.2f}"
        else:
            d, _, pv = pair(runs, ds, c, m)
            test = f"{d:+.4f}, p={pv:.3f}"
        rows.append(dict(dataset=ds, automated=NAME[c], matched_by=NAME[m], difference=test,
                         cost_to_match=f"{s[c] / s[m]:,.0f}x"))
    out += ["## Cost to match", "", md(pd.DataFrame(rows)), ""]

    # Explanation quality
    cols = dict(agree_shap_pfi_tau__mean="tau_SHAP_PFI", faithfulness_corr__mean="faithfulness",
                deletion_gain__mean="deletion", insertion_gain__mean="insertion",
                seed_stability_tau_common="stability", effective_n_features__mean="effective_features",
                generated_share__mean="generated_share")
    rows = []
    for ds, _, name in TASKS:
        s = summ[summ.dataset == ds].groupby("config")[list(cols)].mean()
        for c in [c for c in ORDER if c in s.index]:
            rows.append(dict(dataset=name, configuration=NAME[c], **{v: round(s.loc[c, k], 3) for k, v in cols.items()}))
    xt = ut[(ut.dataset != "nbaiot") & ut.metric.isin(["agree_shap_pfi_tau", "faithfulness_corr"])][
        ["dataset", "config", "metric", "mean_diff", "p_holm"]].round(4)
    nb = pw[(pw.dataset == "nbaiot") & (pw.feature_mode == "infold20") & pw.metric.isin(
        ["agree_shap_pfi_tau", "faithfulness_corr"])][["dataset", "config", "metric", "mean_diff", "wilcoxon_p_holm"]]
    out += ["## Explanation quality", "", md(pd.DataFrame(rows)), "",
            "Tests against the baseline (Edge-IIoTset, UNSW-NB15: corrected t-test, Holm):", "", md(xt), "",
            "N-BaIoT (Wilcoxon over devices, Holm):", "", md(nb.round(4)), ""]

    open(OUT, "w").write("\n".join(out))
    print("\n".join(out))


if __name__ == "__main__":
    main()
